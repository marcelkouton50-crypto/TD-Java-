public class SommeEntier {
    public static void main(String[] args) {
        // Déclarer les variables
        int nombre1 = 10;
        int nombre2 = 20;

        // Calculer la somme
        int somme = nombre1 + nombre2;

        // Afficher le résultat
        System.out.println("La somme de " + nombre1 + " et " + nombre2 + " est : " + somme);
    }
}